#entrada

numero_1 = int(input(f'Qual o primeiro número?'))
numero_2 = int(input(f'Qual o segundo número?'))

#processamento
soma = numero_1 + numero_2
sub = numero_1 - numero_2
mult = numero_1 * numero_2
div = numero_1 / numero_2

#saída
print(f'A soma é igual a {soma}')
print(f'A subtração é igual a {sub}')
print(f'A multiplicação é igual a {mult}')
print(f'A divisão é igual a {div}')